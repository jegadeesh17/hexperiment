"""The results table of the README, generated from ``results.json`` (pure)."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

BEGIN = "<!-- BEGIN BENCHMARK TABLE (generated by update_readme.py; do not edit) -->"
END = "<!-- END BENCHMARK TABLE -->"

NO_CHECK = "No check is designed for it"
_HEADER = (
    "| Leak type | Mechanism | Designed to catch | Rejected | Caught by "
    "| Mean score, leaky | Mean score, clean |"
)
_RULE = "|---|---|---|---|---|---:|---:|"


def render_block(results: Mapping[str, object]) -> str:
    """The text from ``BEGIN`` to ``END``, both markers included."""
    mechanisms: Sequence[Mapping[str, Any]] = results["mechanisms"]  # type: ignore[assignment]
    clean: Mapping[str, Any] = results["clean"]  # type: ignore[assignment]
    not_measured: Sequence[Mapping[str, Any]] = results["not_measured"]  # type: ignore[assignment]
    lines = [BEGIN, "", _HEADER, _RULE]
    lines += [_mechanism_row(m) for m in mechanisms]
    lines.append(_clean_row(clean))
    lines += ["", "Not measured:", ""]
    lines += [_not_measured_line(n) for n in not_measured]
    lines += ["", f"Source: {results['source']}", "", _versions_line(results), "", END]
    return "\n".join(lines)


def splice_block(readme: str, block: str) -> str:
    """Replace the text between the markers (inclusive) with ``block``."""
    for marker in (BEGIN, END):
        count = readme.count(marker)
        if count != 1:
            raise ValueError(
                f"README.md must contain the marker line {marker!r} exactly once; "
                f"it contains it {count} times."
            )
    start = readme.index(BEGIN)
    end = readme.index(END)
    if end < start:
        raise ValueError("The END marker comes before the BEGIN marker in README.md.")
    return readme[:start] + block + readme[end + len(END) :]


# --- rows -----------------------------------------------------------------------------


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _row(cells: Sequence[object]) -> str:
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _mechanism_row(item: Mapping[str, Any]) -> str:
    designed = item["designed_to_catch"]
    return _row(
        [
            f"{item['leak_type']} {item['leak_type_name']}",
            item["mechanism"],
            ", ".join(designed) if designed else NO_CHECK,
            _rejected_cell(item),
            _ghost_cell(item["by_ghost"]),
            _score(item["mean_score_leaky"]),
            _score(item["mean_score_clean"]),
        ]
    )


def _rejected_cell(item: Mapping[str, Any]) -> str:
    scripts, rejected = item["scripts"], item["rejected"]
    percent = 0 if scripts == 0 else round(100 * rejected / scripts)
    cell = f"{rejected} of {scripts} ({percent}%)"
    for status in ("UNVERIFIED", "ERROR"):
        count = item["statuses"][status]
        if count:
            cell += f", {count} {status.lower()}"
    return cell


def _ghost_cell(by_ghost: Mapping[str, int]) -> str:
    if not by_ghost:
        return "none"
    return ", ".join(f"{name} ({count})" for name, count in by_ghost.items())


def _score(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.4f}"


def _clean_row(clean: Mapping[str, Any]) -> str:
    text = (
        f"clean twins: {clean['false_alarms']} false alarms "
        f"in {clean['scripts']} scripts"
    )
    return _row([text, "", "", "", _ghost_cell(clean["by_ghost"]), "", ""])


def _not_measured_line(item: Mapping[str, Any]) -> str:
    return f"- {item['leak_type']} {item['leak_type_name']}: {item['reason']}"


def _versions_line(results: Mapping[str, object]) -> str:
    environment: Mapping[str, Any] = results["environment"]  # type: ignore[assignment]
    mechanisms: Sequence[Mapping[str, Any]] = results["mechanisms"]  # type: ignore[assignment]
    runs = 2 * sum(m["scripts"] for m in mechanisms)
    date = str(results["created_at"])[:10]
    return (
        f"Run with hexperiment {environment['hexperiment']}, "
        f"Python {environment['python']} and scikit-learn "
        f"{environment['scikit-learn']} on {date}: {runs} runs."
    )
