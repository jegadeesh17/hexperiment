"""The model card: a GitHub-flavoured Markdown rendering of one verdict.

``render`` is pure. It reads no file and no clock; ``runs.finalize_run`` writes the
text it returns.
"""

from __future__ import annotations

import json
import re
from collections.abc import Sequence

from hexperiment.models import DataSummary, Finding, Verdict

NOTICE = "Generated by hexperiment. Do not edit by hand."

_EMPTY_CELL = "-"
_LEADING_MARKUP = re.compile(r"^(?=[#>+\-*`~<])")


def render(
    verdict: Verdict, history: Sequence[Verdict], *, description: str = ""
) -> str:
    """Return the model card for ``verdict`` (Requirements 14.1 to 14.3).

    ``history`` holds the earlier verdicts of the app, oldest first, without
    ``verdict`` itself. ``description`` is the app description from ``hex.toml``;
    a ``Verdict`` does not carry it. The sections follow the order in the design:
    title, status, notice, data, metric, checks, findings, waivers, test-set uses,
    run history.
    """
    sections = [
        _title(verdict, description),
        _status(verdict),
        f"> {NOTICE}",
        _data(verdict),
        _metric(verdict),
        _checks(verdict),
        _findings(verdict),
        _waivers(verdict),
        _test_set_uses(verdict),
        _history(history),
    ]
    return "\n\n".join(sections) + "\n"


def _cell(text: object) -> str:
    """One table cell: backslashes and pipes escaped, newlines folded, trimmed."""
    flat = " ".join(str(text).splitlines()).strip()
    escaped = flat.replace("\\", "\\\\").replace("|", "\\|")
    return escaped or _EMPTY_CELL


def _line(text: str) -> str:
    """Text for a heading or a paragraph: whitespace folded, leading markup escaped."""
    flat = " ".join(text.split())
    return _LEADING_MARKUP.sub(r"\\", flat)


def _table(headers: Sequence[str], rows: Sequence[Sequence[object]]) -> str:
    lines = [_row(headers), _row(["---"] * len(headers))]
    lines.extend(_row([_cell(value) for value in row]) for row in rows)
    return "\n".join(lines)


def _row(cells: Sequence[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _title(verdict: Verdict, description: str) -> str:
    title = f"# {_line(verdict.app) or 'model card'}"
    text = _line(description)
    return f"{title}\n\n{text}" if text else title


def _status(verdict: Verdict) -> str:
    return "\n".join(
        [
            "## Status",
            "",
            f"- **Verdict:** {verdict.status.value}",
            f"- **Mode:** {verdict.mode.value}",
            f"- **Run id:** {_line(verdict.run_id)}",
            f"- **Date:** {_line(verdict.created_at)}",
            f"- **hexperiment version:** {_line(verdict.hexperiment_version)}",
        ]
    )


def _data(verdict: Verdict) -> str:
    data = verdict.data
    if data is None:
        return "## Data\n\nNot available: the run stopped on an input error."
    lines = [
        "## Data",
        "",
        f"- **Training rows:** {data.n_train} "
        f"(positive rate {data.positive_rate_train:.1%})",
        f"- **Test rows:** {data.n_test} "
        f"(positive rate {data.positive_rate_test:.1%})",
    ]
    lines.extend(_time_lines(verdict, data))
    return "\n".join(lines)


def _time_lines(verdict: Verdict, data: DataSummary) -> list[str]:
    if verdict.split.time_column is None:
        return []
    lines = [f"- **Time column:** {_line(verdict.split.time_column)}"]
    for label, span in (
        ("Training time range", data.train_time_range),
        ("Test time range", data.test_time_range),
    ):
        if span is not None:
            lines.append(f"- **{label}:** {_line(span[0])} to {_line(span[1])}")
    return lines


def _metric(verdict: Verdict) -> str:
    metric = verdict.metric
    if metric.value is None:
        value = "not computed"
        outcome = "failed"
    else:
        value = f"{metric.value:.4f}"
        outcome = "passed" if metric.passed else "failed"
    return (
        "## Metric\n\n"
        f"- **{_line(metric.name)}:** {value}\n"
        f"- **Threshold:** {metric.threshold:.4f}\n"
        f"- **Result:** {outcome}"
    )


def _checks(verdict: Verdict) -> str:
    if not verdict.checks:
        return "## Checks\n\nNo checks ran."
    rows = [(c.name, c.ghost or _EMPTY_CELL, c.outcome.value) for c in verdict.checks]
    return "## Checks\n\n" + _table(["Check", "Ghost", "Outcome"], rows)


def _findings(verdict: Verdict) -> str:
    if not verdict.findings:
        return "## Findings\n\nNo findings."
    headers = [
        "Severity",
        "Ghost",
        "Location",
        "Message",
        "Evidence",
        "Fix hint",
        "Waiver reason",
    ]
    rows = [_finding_row(f) for f in verdict.findings]
    return "## Findings\n\n" + _table(headers, rows)


def _finding_row(finding: Finding) -> list[object]:
    return [
        finding.severity.value,
        finding.ghost or finding.check,
        finding.location,
        finding.message,
        json.dumps(finding.evidence, sort_keys=True, ensure_ascii=False, default=str),
        finding.fix,
        finding.waiver_reason or "",
    ]


def _waivers(verdict: Verdict) -> str:
    if not verdict.waivers:
        return "## Waivers\n\nNo waivers applied."
    rows = [
        (w.check, w.column or "all columns", w.reason, w.findings_waived)
        for w in verdict.waivers
    ]
    headers = ["Check", "Column", "Reason", "Findings waived"]
    return "## Waivers\n\n" + _table(headers, rows)


def _test_set_uses(verdict: Verdict) -> str:
    return (
        "## Test-set uses\n\n"
        f"The test set has been evaluated {verdict.test_set_uses} time(s), "
        "including this run."
    )


def _history(history: Sequence[Verdict]) -> str:
    if not history:
        return "## Run history\n\nnone"
    rows = [
        (v.run_id, v.status.value, _metric_value(v)) for v in history
    ]
    return (
        "## Run history\n\n"
        "Earlier runs of this app, oldest first.\n\n"
        + _table(["Run id", "Status", "Metric"], rows)
    )


def _metric_value(verdict: Verdict) -> str:
    value = verdict.metric.value
    return _EMPTY_CELL if value is None else f"{value:.4f}"
