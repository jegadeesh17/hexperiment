# --- property ------------------------------------------------------------------------

text = st.text(max_size=40)
evidence = st.dictionaries(
    text,
    st.one_of(text, st.integers(), st.booleans(), st.none()),
    max_size=4,
)
severities = st.sampled_from(list(Severity))


@st.composite
def hostile_verdicts(draw) -> Verdict:
    severity = draw(severities)
    finding = make_finding(
        severity=severity,
        check=draw(text),
        ghost=draw(st.none() | text),
        location=draw(text),
        fix=draw(text),
        reason=draw(text) if severity is Severity.WAIVED else None,
        evidence=draw(evidence),
    )
    return make_verdict(
        app=draw(text),
        run_id=draw(text),
        checks=(CheckSummary(draw(text), draw(st.none() | text), Outcome.PASSED),),
        findings=(finding,),
        waivers=(WaiverRecord(draw(text), draw(st.none() | text), draw(text), 1),),
    )


def folded(value: str) -> str:
    return " ".join(value.splitlines()).strip() or "-"


@given(hostile_verdicts(), hostile_verdicts(), text)
def test_every_table_row_has_the_header_cell_count(verdict, earlier, description):
    card = render(verdict, [earlier], description=description)
    found = tables(card)
    assert len(found) == 4
    for table in found:
        assert {len(row) for row in table} == {len(table[0])}


@given(hostile_verdicts(), hostile_verdicts())
def test_table_cells_unescape_to_the_original_text(verdict, earlier):
    card = render(verdict, [earlier])
    checks, findings, waivers, history = tables(card)
    check = verdict.checks[0]
    finding = verdict.findings[0]
    waiver = verdict.waivers[0]
    assert checks[1][0] == folded(check.name)
    assert findings[1][2] == folded(finding.location)
    assert findings[1][5] == folded(finding.fix)
    assert waivers[1][2] == folded(waiver.reason)
    assert history[1][0] == folded(earlier.run_id)
