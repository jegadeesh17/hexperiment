REASON = "Tenure is known at prediction time and is legitimately strong."
FIX = "check whether this column is recorded after the outcome; if so, drop it"
DELIMITER = re.compile(r"^(\| --- )+\|$")


def make_finding(
    severity: Severity = Severity.ERROR,
    check: str = "target_proxy",
    ghost: str | None = "The Possession",
    location: str = "tenure_months",
    fix: str = FIX,
    reason: str | None = None,
    evidence: dict | None = None,
) -> Finding:
    return Finding(
        check=check,
        ghost=ghost,
        severity=severity,
        location=location,
        message=f"{location} alone predicts the target",
        evidence={"score": 0.96, "threshold": 0.95} if evidence is None else evidence,
        fix=fix,
        waiver_reason=reason,
    )


def make_verdict(**changes) -> Verdict:
    base = Verdict(
        status=Status.REJECTED,
        mode=RunMode.FULL,
        app="churn",
        run_id="20251101-093012-a1b2c3",
        created_at="2025-11-01T09:30:12Z",
        hexperiment_version="0.1.0",
        metric=MetricResult("roc_auc", 0.873412, 0.8, True),
        checks=(
            CheckSummary("row_overlap", "The Doppelganger", Outcome.PASSED),
            CheckSummary("split_order", None, Outcome.PASSED),
            CheckSummary("canary", "The Peeking Spirit", Outcome.FAILED),
        ),
        findings=(make_finding(),),
        waivers=(),
        test_set_uses=3,
        split=SplitSignature("data/churn.csv", 0.2, 0, None),
        data=DataSummary(5613, 1387, 0.265454, 0.270368, None, None),
    )
    return replace(base, **changes)


def sections(card: str) -> dict[str, str]:
    parts = re.split(r"^## (.+)$", card, flags=re.MULTILINE)
    return {parts[i]: parts[i + 1] for i in range(1, len(parts), 2)}


def split_row(line: str) -> list[str]:
    """Cells of a table row, split on unescaped pipes and unescaped."""
    cells: list[str] = []
    current: list[str] = []
    i = 1
    assert line.startswith("|")
    while i < len(line):
        char = line[i]
        if char == "\\" and i + 1 < len(line):
            current.append(line[i + 1])
            i += 2
            continue
        if char == "|":
            cells.append("".join(current))
            current = []
        else:
            current.append(char)
        i += 1
    assert not current, "row does not end with an unescaped pipe"
    return [cell.removeprefix(" ").removesuffix(" ") for cell in cells]


def tables(card: str) -> list[list[list[str]]]:
    """Every GFM table in the card, as rows of cells (header first)."""
    lines = card.split("\n")
    found = []
    for i in range(len(lines) - 1):
        if not lines[i].startswith("|") or not DELIMITER.match(lines[i + 1]):
            continue
        rows = [split_row(lines[i])]
        j = i + 2
        while j < len(lines) and lines[j].startswith("|"):
            rows.append(split_row(lines[j]))
            j += 1
        found.append(rows)
    return found


