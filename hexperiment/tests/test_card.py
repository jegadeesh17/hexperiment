def test_every_table_is_preceded_by_a_blank_line_and_has_equal_row_widths():
    waivers = (WaiverRecord("target_proxy", "tenure_months", REASON, 1),)
    card = render(make_verdict(waivers=waivers), [make_verdict()])
    lines = card.split("\n")
    found = tables(card)
    assert len(found) == 4
    for i, line in enumerate(lines[:-1]):
        if line.startswith("|") and DELIMITER.match(lines[i + 1]):
            assert lines[i - 1] == ""
    for table in found:
        assert {len(row) for row in table} == {len(table[0])}


